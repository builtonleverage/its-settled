# Generates the PNG app icons as base64 into src/icons.js (no build step needed at deploy time).
#   python3 scripts/make-icons.py
import base64, io, os
from PIL import Image, ImageDraw

GREEN, WHITE = (31, 107, 85, 255), (255, 255, 255, 255)
CHECK = [(146, 268), (220, 342), (366, 172)]   # same tick as icon.svg (512 viewBox)

def icon(size, rounded, scale=1.0):
    S = size * 4                                # draw at 4x, then downsample for smooth edges
    im = Image.new('RGBA', (S, S), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    if rounded: d.rounded_rectangle([0, 0, S - 1, S - 1], radius=int(S * 0.22), fill=GREEN)
    else: d.rectangle([0, 0, S, S], fill=GREEN)
    k, c = S / 512 * scale, S / 2
    pts = [(c + (x - 256) * k, c + (y - 256) * k) for x, y in CHECK]
    w = int(56 * k)
    d.line(pts, fill=WHITE, width=w, joint='curve')
    for x, y in (pts[0], pts[-1]): d.ellipse([x - w / 2, y - w / 2, x + w / 2, y + w / 2], fill=WHITE)
    out = io.BytesIO(); im.resize((size, size), Image.LANCZOS).save(out, 'PNG', optimize=True)
    return base64.b64encode(out.getvalue()).decode()

icons = {
    'icon-180.png': icon(180, False),                 # iOS home screen (iOS rounds the corners itself)
    'icon-192.png': icon(192, True),
    'icon-512.png': icon(512, True),
    'icon-maskable-512.png': icon(512, False, 0.72),  # Android masks: keep the tick inside the safe zone
}
path = os.path.join(os.path.dirname(__file__), '..', 'src', 'icons.js')
with open(path, 'w') as f:
    f.write('// Generated by scripts/make-icons.py. Base64 PNG app icons served by the Worker.\nexport const PNG_ICONS = {\n')
    for k, v in icons.items(): f.write(f"  '{k}': '{v}',\n")
    f.write('};\n')
print({k: len(v) * 3 // 4 for k, v in icons.items()}, 'bytes')
